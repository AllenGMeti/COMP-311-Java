public class Question_1 {
    public static void main(String[] args) {

        int count = 10;

        // Loop for count down from 10 to 1
        while (count >= 1) {
            System.out.println(count);
            count--; 
        }

        // Printing liftoff message
        System.out.println("Liftoff!");
    }
}